import { test, expect } from '../../src/Web/node_modules/@playwright/test/index.mjs'

test('Kalenderperioden, belegte Energieflüsse und Uhrzeit-Drilldown', async ({ page }) => {
  await page.goto('/?kind=season&anchor=2026-09-10')
  await expect(page.getByText('Herbst 2026', { exact: true })).toBeVisible()
  await expect(page.getByText('1.9.2026 bis 30.11.2026', { exact: true })).toBeVisible()
  await expect(page.getByText(/Letzter abgedeckter Tag/)).toContainText('31.10.2026')
  await page.getByRole('combobox', { name: 'Jahreszeit', exact: true }).selectOption({ label: 'Winter' })
  await expect(page.getByText('Winter 2026/27', { exact: true })).toBeVisible()
  const year = page.getByRole('combobox', { name: 'Jahr', exact: true })
  await year.selectOption('2025')
  await expect(page.getByText('Winter 2025/26', { exact: true })).toBeVisible()
  await year.selectOption('2026')
  await page.getByRole('combobox', { name: 'Zeitraum', exact: true }).selectOption('quarter')
  await expect(page.getByText('Q4 2026', { exact: true })).toBeVisible()
  const quarter = page.getByRole('combobox', { name: 'Quartal', exact: true })
  await quarter.selectOption({ label: 'Q2' })
  await expect(page.getByText('Q2 2026', { exact: true })).toBeVisible()
  await quarter.selectOption({ label: 'Q4' })
  await page.getByRole('button', { name: 'Nächster Zeitraum' }).click()
  await expect(page.getByText('Q1 2027', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Vorheriger Zeitraum' }).click()
  await expect(page.getByText('Q4 2026', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Zeitraum', exact: true }).selectOption('month')
  await expect(page.getByText('Oktober 2026', { exact: true })).toBeVisible()
  const month = page.getByRole('combobox', { name: 'Monat', exact: true })
  await month.selectOption({ label: 'September' })
  await expect(page.getByText('September 2026', { exact: true })).toBeVisible()
  await month.selectOption({ label: 'Oktober' })
  await expect(page.getByRole('img', { name: 'Woher kam mein Haushaltsstrom?' })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Wohin ging mein PV-Ertrag?' })).toBeVisible()
  await page.getByLabel('Reine Speicherzustände anzeigen').check()
  await page.getByRole('button', { name: '03:00–04:00', exact: true }).first().click()
  const evidence = page.getByRole('heading', { name: 'Belegende Tage · 03:00–04:00' }).locator('..')
  await evidence.getByRole('table').getByRole('button').first().click()
  await expect(page.getByRole('img', { name: 'Gestapelte Haushaltslast aus PV, Speicher und Netz' })).toBeVisible()
  await page.getByRole('button', { name: 'Zurück zum Zeitraum' }).click()
  await expect(page.getByText('Oktober 2026', { exact: true })).toBeVisible()
  await page.goto('/?kind=week&anchor=2027-01-01')
  await expect(page.getByText('KW 53 2026', { exact: true })).toBeVisible()
  await expect(page.getByText('28.12.2026 bis 3.1.2027', { exact: true })).toBeVisible()
})
